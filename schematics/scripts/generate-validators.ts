#!/usr/bin/env bun

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Ajv2020 } from 'ajv/dist/2020.js';
import standalone from 'ajv/dist/standalone/index.js';

const standaloneCode = standalone.default;

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const schemasDir = path.join(root, 'schemas');
const indexOutput = path.join(root, 'packages/validation/generated-validators.ts');
const typeDir = path.join(root, 'packages/validation/generated-validators');
const diagramTypes = ['workflow', 'sequence', 'dataflow', 'lifecycle', 'architecture', 'erd', 'tree', 'class', 'timeline', 'waterfall', 'explainer'];
const commonSchema: object = JSON.parse(fs.readFileSync(path.join(schemasDir, 'common.schema.json'), 'utf8'));

const banner = '// Generated by scripts/generate-validators.ts. Do not edit by hand.\n';
const ajvUcs2Import = 'require("ajv/dist/runtime/ucs2length").default';
const inlineUcs2Length = `function ucs2length(str) {
  const len = str.length;
  let length = 0;
  let pos = 0;
  while (pos < len) {
    length += 1;
    const value = str.charCodeAt(pos++);
    if (value >= 0xd800 && value <= 0xdbff && pos < len
      && (str.charCodeAt(pos) & 0xfc00) === 0xdc00) pos += 1;
  }
  return length;
}`;
let sawUcs2Helper = false;
function typeValidatorSource(type: string): string {
  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    code: { source: true, esm: true },
  });
  ajv.addSchema(commonSchema);
  const schema: { $id: string } = JSON.parse(fs.readFileSync(path.join(schemasDir, `${type}.schema.json`), 'utf8'));
  ajv.addSchema(schema);
  let validatorCode = standaloneCode(ajv, { [type]: schema.$id });
  if (validatorCode.includes(ajvUcs2Import)) sawUcs2Helper = true;
  validatorCode = validatorCode.replaceAll(ajvUcs2Import, inlineUcs2Length);
  if (validatorCode.includes('require(')) {
    throw new Error('AJV standalone output contains an unexpected runtime dependency');
  }
  const exportPattern = new RegExp(`export const ${type} = (validate\\d+);`);
  const match = validatorCode.match(exportPattern);
  if (!match) throw new Error(`AJV standalone output no longer exports the ${type} validator as expected`);
  validatorCode = validatorCode.replace(exportPattern, `const schemaValidate = ${match[1]};`);
  return `${banner}import { validatePortablePath } from '../../output/portable-path.ts';
${validatorCode}
export function validate(data, context = undefined) {
  if (!schemaValidate(data, context)) {
    validate.errors = schemaValidate.errors;
    return false;
  }
  const output = data?.meta?.output;
  if (typeof output === 'string') {
    try {
      validatePortablePath(output, { profile: 'output' });
    } catch (error) {
      validate.errors = [{
        instancePath: \`${'${context?.instancePath || \'\'}'}/meta/output\`,
        schemaPath: 'common.schema.json#/$defs/portableOutputPath',
        keyword: 'portablePath',
        params: { reason: error?.reason || 'invalid' },
        message: 'must satisfy the portable output path contract',
      }];
      return false;
    }
  }
  validate.errors = null;
  return true;
}
validate.evaluated = schemaValidate.evaluated;
`;
}

const outputs = new Map<string, string>();
for (const type of diagramTypes) outputs.set(path.join(typeDir, `${type}.js`), typeValidatorSource(type));
if (!sawUcs2Helper) {
  throw new Error('AJV standalone output no longer contains the expected ucs2length helper');
}

// A diagram type that is a reserved word (`class`) cannot name a function, so
// it is defined under a safe local name and exported under the type itself.
const RESERVED_TYPE_NAMES = new Set(['class']);
const indexExports = diagramTypes.map((type) => {
  const name = RESERVED_TYPE_NAMES.has(type) ? `${type}Diagram` : type;
  return name === type
    ? `export const ${type} = lazyValidator('${type}');`
    : `const ${name} = lazyValidator('${type}');\nexport { ${name} as ${type} };`;
}).join('\n');
outputs.set(indexOutput, `${banner}import { createRequire } from 'node:module';

export interface SchemaError {
  instancePath: string;
  schemaPath: string;
  keyword: string;
  params: Record<string, unknown>;
  message?: string;
  schema?: unknown;
}

export interface SchemaValidator {
  (data: unknown, context?: unknown): boolean;
  errors?: SchemaError[] | null;
}

const requireValidator = createRequire(import.meta.url);

function loadValidator(type: string): SchemaValidator {
  const module: { validate: SchemaValidator } = requireValidator(\`./generated-validators/\${type}.js\`);
  return module.validate;
}

function lazyValidator(type: string): SchemaValidator {
  let loaded: SchemaValidator | undefined;
  const validate: SchemaValidator = (data: unknown, context: unknown = undefined): boolean => {
    loaded ??= loadValidator(type);
    const valid = loaded(data, context);
    validate.errors = loaded.errors;
    return valid;
  };
  return validate;
}

${indexExports}
`);

if (process.argv.includes('--check')) {
  const expectedTypeFiles = new Set(diagramTypes.map((type) => `${type}.js`));
  const strayTypeFiles = fs.existsSync(typeDir)
    ? fs.readdirSync(typeDir).filter((name) => !expectedTypeFiles.has(name))
    : [];
  const stale = [...outputs].filter(([file, source]) => {
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n?/g, '\n') : '';
    return current !== source;
  });
  if (stale.length || strayTypeFiles.length) {
    console.error('generated validators are stale — run bun run generate:validators');
    process.exit(1);
  }
} else {
  fs.mkdirSync(typeDir, { recursive: true });
  for (const [file, source] of outputs) {
    const temporary = `${file}.${process.pid}.tmp`;
    fs.writeFileSync(temporary, source);
    fs.renameSync(temporary, file);
    console.log(`generated ${path.relative(root, file)}`);
  }
}
